// =============================================================
// 福祉・介護分野の重点テーマ（5テーマ）
//
// 政策ページ（/vision/）の福祉・介護カードで、
//   ① 公的データで確認できた現状
//   ② そこから考えられる論点
//   ③ 現在の延岡市の取り組み
//   ④ 今後検討したい提言
// という流れを、市民の方にも分かる形で示すためのデータです。
//
// -------------------------------------------------------------
// 【書くときの絶対ルール】
//
// 1. 「事実」と「意見」を必ず分ける
//    ・situation（現状）には、公的資料で確認できた事実だけを書く。
//    ・discussionPoints（論点）は「〜が論点となります」という書き方にし、
//      「数値が○○だから△△が不足している」という断定はしない。
//
// 2. 市の既存施策を無視しない
//    ・currentEfforts には、延岡市が実際に実施している施策だけを、
//      公式ページで確認したうえで正式名称のまま書く。
//    ・「何も行われていない」という趣旨の表現は書かない。
//
// 3. 提言は確定公約として書かない
//    ・proposals は「検討している提言」。断定・公約表現は使わない。
//
// 4. 数値はここに書かない
//    ・数値は src/data/vision.ts の evidenceItems で一元管理している。
//      ここでは evidenceLabels でその label を参照するだけにする
//      （二重管理による食い違いを防ぐため）。
// =============================================================

export interface WelfareEffort {
  /** 施策の正式名称（延岡市の公式ページの表記をそのまま使う） */
  name: string;
  /** 何をしている施策かの短い説明（公式ページの記載に基づく） */
  description: string;
  /** 出典となる延岡市公式ページのURL */
  sourceUrl: string;
  /** 内容を確認した日（"YYYY-MM-DD"） */
  confirmedDate: string;
}

export interface WelfareTheme {
  id: string;
  /** テーマ名 */
  title: string;
  /** 1〜2文の要約 */
  summary: string;
  /** 現状（公的資料で確認できた事実のみ） */
  situation: string[];
  /**
   * このテーマに関係する指標の label。
   * src/data/vision.ts の evidenceItems の label と完全に一致させること。
   */
  evidenceLabels: string[];
  /** 現在の延岡市の取り組み（実施が確認できたものだけ） */
  currentEfforts: WelfareEffort[];
  /** 今後の論点（断定を避けた問いの形で書く） */
  discussionPoints: string[];
  /** 検討している提言（確定公約としては書かない） */
  proposals: string[];
}

